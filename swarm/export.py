"""Turn a parameter set into a self-contained, uploadable agent bundle."""

from __future__ import annotations

import pprint
import py_compile
import re
import shutil
from pathlib import Path
from typing import Any

from .families import COMMON, family as get_family
from .tournament import REPO

AGENTS_DIR = REPO / "src" / "dme_simulator" / "agents"

TEMPLATE = '''"""Generated by `swarm export` ({family} family) from {source}."""

from .{module} import AGENT as _Strategy


class {class_name}(_Strategy):
    PARAMS = {params}

    def __init__(self) -> None:
        super().__init__()
'''


def export_bundle(
    params: dict[str, Any], name: str, source: str = "?", directory: Path | None = None,
    overwrite: bool = False, family: str | None = None,
) -> Path:
    fam = get_family(family)
    if not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.\- ]*", name):
        raise ValueError(f"invalid bundle name: {name!r}")
    full = fam.complete(params)
    target = (directory or AGENTS_DIR) / name
    if target.exists():
        if not overwrite:
            raise FileExistsError(f"{target} exists; pass --overwrite to replace it")
        shutil.rmtree(target)
    target.mkdir(parents=True)
    module = fam.source.stem
    shutil.copy(fam.source, target / fam.source.name)
    shutil.copy(COMMON, target / COMMON.name)
    for helper in fam.helpers:
        shutil.copy(helper, target / helper.name)
    class_name = "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]", name) if part) or "Swarm"
    if class_name[0].isdigit():
        class_name = "Agent" + class_name
    (target / "agent.py").write_text(
        TEMPLATE.format(
            family=fam.name,
            source=source,
            module=module,
            class_name=class_name,
            params=pprint.pformat(full, sort_dicts=False, width=60).replace("\n", "\n" + " " * 13),
        )
    )
    for file in target.glob("*.py"):
        py_compile.compile(str(file), doraise=True)
    shutil.rmtree(target / "__pycache__", ignore_errors=True)
    return target
