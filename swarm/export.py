"""Turn a parameter set into a self-contained, uploadable agent bundle."""

from __future__ import annotations

import pprint
import py_compile
import re
import shutil
from pathlib import Path
from typing import Any

from .strategy import DEFAULT_PARAMS
from .tournament import REPO

AGENTS_DIR = REPO / "src" / "dme_simulator" / "agents"

TEMPLATE = '''"""Generated by `swarm export` from {source}."""

from .strategy import ParamAgent


class {class_name}(ParamAgent):
    PARAMS = {params}

    def __init__(self) -> None:
        super().__init__()
'''


def export_bundle(
    params: dict[str, Any], name: str, source: str = "?", directory: Path | None = None,
    overwrite: bool = False,
) -> Path:
    if not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.\- ]*", name):
        raise ValueError(f"invalid bundle name: {name!r}")
    unknown = set(params) - set(DEFAULT_PARAMS)
    if unknown:
        raise ValueError(f"unknown parameters: {sorted(unknown)}")
    target = (directory or AGENTS_DIR) / name
    if target.exists():
        if not overwrite:
            raise FileExistsError(f"{target} exists; pass --overwrite to replace it")
        shutil.rmtree(target)
    target.mkdir(parents=True)
    shutil.copy(Path(__file__).parent / "strategy.py", target / "strategy.py")
    full = {**DEFAULT_PARAMS, **params}
    class_name = "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]", name) if part) or "Swarm"
    if class_name[0].isdigit():
        class_name = "Agent" + class_name
    (target / "agent.py").write_text(
        TEMPLATE.format(
            source=source,
            class_name=class_name,
            params=pprint.pformat(full, sort_dicts=False, width=60).replace("\n", "\n" + " " * 13),
        )
    )
    for file in ("agent.py", "strategy.py"):
        py_compile.compile(str(target / file), doraise=True, cfile=None)
    shutil.rmtree(target / "__pycache__", ignore_errors=True)
    return target
